-- Student Commute Survey: Supabase setup
-- Review existing tables and policies before running this script in a project
-- that already contains survey data.

create table if not exists public.survey_responses (
    id bigint generated by default as identity primary key,
    answers jsonb not null check (jsonb_typeof(answers) = 'object'),
    created_at timestamptz not null default now()
);

alter table public.survey_responses enable row level security;

-- Remove existing SELECT policies so public clients cannot read individual rows.
do $$
declare
    policy_row record;
begin
    for policy_row in
        select policyname
        from pg_policies
        where schemaname = 'public'
          and tablename = 'survey_responses'
          and cmd = 'SELECT'
    loop
        execute format(
            'drop policy if exists %I on public.survey_responses',
            policy_row.policyname
        );
    end loop;
end;
$$;

drop policy if exists "Allow anonymous survey submissions" on public.survey_responses;
create policy "Allow anonymous survey submissions"
on public.survey_responses
for insert
to anon
with check (
    jsonb_typeof(answers) = 'object'
    and answers ? 'transport'
    and answers ? 'duration'
    and answers ? 'satisfaction'
);

revoke all on table public.survey_responses from anon, authenticated;
grant insert on table public.survey_responses to anon;

-- Identity sequence used by the table's generated id.
grant usage on sequence public.survey_responses_id_seq to anon;

create or replace function public.get_survey_stats()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    response_total integer;
    transport_json jsonb;
    duration_json jsonb;
    factor_json jsonb;
    satisfaction_avg numeric;
begin
    select count(*)::integer
    into response_total
    from public.survey_responses;

    if response_total < 5 then
        return jsonb_build_object(
            'total', response_total,
            'transport_counts', '{}'::jsonb,
            'duration_counts', '{}'::jsonb,
            'factor_counts', '{}'::jsonb,
            'avg_satisfaction', null
        );
    end if;

    select coalesce(jsonb_object_agg(category, category_count), '{}'::jsonb)
    into transport_json
    from (
        select answers->>'transport' as category, count(*)::integer as category_count
        from public.survey_responses
        where nullif(answers->>'transport', '') is not null
        group by answers->>'transport'
        having count(*) >= 5
    ) grouped_transport;

    select coalesce(jsonb_object_agg(category, category_count), '{}'::jsonb)
    into duration_json
    from (
        select answers->>'duration' as category, count(*)::integer as category_count
        from public.survey_responses
        where nullif(answers->>'duration', '') is not null
        group by answers->>'duration'
        having count(*) >= 5
    ) grouped_duration;

    select coalesce(jsonb_object_agg(category, category_count), '{}'::jsonb)
    into factor_json
    from (
        select factor as category, count(*)::integer as category_count
        from public.survey_responses
        cross join lateral jsonb_array_elements_text(
            case
                when jsonb_typeof(answers->'choice_factors') = 'array'
                then answers->'choice_factors'
                else '[]'::jsonb
            end
        ) as factors(factor)
        group by factor
        having count(*) >= 5
    ) grouped_factors;

    select round(avg((answers->>'satisfaction')::numeric), 1)
    into satisfaction_avg
    from public.survey_responses
    where (answers->>'satisfaction') ~ '^[0-9]+(\.[0-9]+)?$'
      and (answers->>'satisfaction')::numeric between 1 and 10;

    return jsonb_build_object(
        'total', response_total,
        'transport_counts', transport_json,
        'duration_counts', duration_json,
        'factor_counts', factor_json,
        'avg_satisfaction', satisfaction_avg
    );
end;
$$;

revoke all on function public.get_survey_stats() from public;
grant execute on function public.get_survey_stats() to anon, authenticated;
